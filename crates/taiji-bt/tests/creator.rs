//! Creator acceptance tests.
//!
//! Strongest check: generating from the same material as
//! `tests/fixtures/hybrid_16k.torrent` (same files / piece length / name /
//! announce) must reproduce the fixture **byte for byte**, including both
//! infohashes and piece layers (the fixture's expected values were
//! interop-verified against libtorrent 2.1.1.0).
//!
//! The rest: three forms x single/multi-file x short-tail/pad alignment x
//! attr matrix + a roundtrip property — every generated torrent must pass
//! all existing parse faces (`filetree::parse` / `parse_v1_files` /
//! `detect_swarm_kind` / piece layers re-validation) without warnings.

use std::fs;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};

use proptest::prelude::*;
use sha1::{Digest as _, Sha1};
use sha2::Sha256;
use taiji_bt::bencode::{Value, decode_with_info_span};
use taiji_bt::creator::{
    CreateFile, CreateRequest, CreatedTorrent, CreatorError, TorrentForm, create, create_blocking,
};
use taiji_bt::filetree::{self, FileAttr, SwarmKind};

const EXPECTED_V1: &str = "9e4fb011b72c9ebdf1152175a20fe4e9f5a866a0";
const EXPECTED_V2: &str = "d7f59962f0b19ab34dbad44ea906d9f270806fedab6eff552ebef9cfa8f8cb40";

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// Unique temp dir (inline std::fs; an in-process counter avoids
/// collisions).
fn temp_dir(tag: &str) -> PathBuf {
    static COUNTER: AtomicUsize = AtomicUsize::new(0);
    let dir = std::env::temp_dir().join(format!(
        "bh-creator-p100-{}-{}-{}",
        std::process::id(),
        COUNTER.fetch_add(1, Ordering::Relaxed),
        tag
    ));
    fs::create_dir_all(&dir).unwrap_or_else(|e| panic!("create temp dir {dir:?}: {e}"));
    dir
}

/// Fixture-equivalent material: the deterministic payloads the fixture was
/// generated from.
fn content_a() -> Vec<u8> {
    (0..70000u32).map(|i| ((i * 7 + 11) % 256) as u8).collect()
}

fn content_b() -> Vec<u8> {
    (0..30000u32).map(|i| ((i * 13 + 29) % 256) as u8).collect()
}

fn write_file(dir: &Path, name: &str, content: &[u8]) -> PathBuf {
    let p = dir.join(name);
    if let Some(parent) = p.parent() {
        fs::create_dir_all(parent).unwrap_or_else(|e| panic!("mkdir {parent:?}: {e}"));
    }
    fs::write(&p, content).unwrap_or_else(|e| panic!("write {p:?}: {e}"));
    p
}

fn creator_file(dir: &Path, name: &str, content: &[u8], attr: FileAttr) -> CreateFile {
    CreateFile {
        path: PathBuf::from(name),
        source: write_file(dir, name, content),
        length: content.len() as u64,
        attr,
    }
}

fn base_request(name: &str, files: Vec<CreateFile>, form: TorrentForm) -> CreateRequest {
    CreateRequest {
        name: name.to_string(),
        files,
        piece_length: 16 * 1024,
        form,
        private: false,
        announce: None,
        announce_list: None,
        comment: None,
        creation_date: None,
    }
}

fn get<'a>(value: &'a Value, key: &[u8]) -> &'a Value {
    match value.get(key) {
        Some(v) => v,
        None => panic!("missing dict key {key:?}"),
    }
}

fn ok<T, E: std::fmt::Debug>(r: Result<T, E>, what: &str) -> T {
    match r {
        Ok(v) => v,
        Err(e) => panic!("{what}: {e:?}"),
    }
}

/// Self-validation loop: the generated torrent passes every existing parse
/// face cleanly + both infohashes recompute over the raw slice (half of
/// the roundtrip invariant).
fn self_validate(created: &CreatedTorrent, form: TorrentForm, want_lengths: &[u64]) {
    let (top, span) = ok(
        decode_with_info_span(&created.bytes),
        "decode generated bytes",
    );
    assert_eq!(span, created.info_span, "info span self-consistent");
    assert_eq!(
        filetree::detect_swarm_kind(&top).unwrap_or_else(|e| panic!("detect_swarm_kind: {e}")),
        form,
        "swarm kind must match the requested form"
    );
    // dual infohashes: independent recompute over the raw slice.
    let raw = &created.bytes[span.clone()];
    assert_eq!(
        hex(&Sha1::digest(raw)),
        hex(&created.info_hash_v1),
        "v1 infohash"
    );
    assert_eq!(
        hex(&Sha256::digest(raw)),
        hex(&created.info_hash_v2),
        "v2 infohash"
    );

    // v2 face: file tree + piece layers re-validation (built into parse,
    // the BEP-52 invalid-torrent criterion). v2 DFS order = key byte order
    // (not the v1 layout order), so compare as multisets.
    if matches!(form, SwarmKind::V2Only | SwarmKind::Hybrid) {
        let files = ok(filetree::parse(&top), "filetree::parse");
        let mut got: Vec<u64> = files.files.iter().map(|f| f.length).collect();
        got.sort_unstable();
        let mut want: Vec<u64> = want_lengths.to_vec();
        want.sort_unstable();
        assert_eq!(got, want, "file tree file-length set matches the input");
    }
    // v1 face: files list + pad offsets (BEP-47).
    if matches!(form, SwarmKind::V1Only | SwarmKind::Hybrid) {
        let files = ok(filetree::parse_v1_files(&top), "parse_v1_files");
        let real: Vec<&filetree::FileEntry> =
            files.files.iter().filter(|f| !f.attr.padding).collect();
        let got: Vec<u64> = real.iter().map(|f| f.length).collect();
        assert_eq!(
            &got, want_lengths,
            "v1 files non-pad file-length set matches the input"
        );
        // pad alignment: every file after a pad starts at a piece boundary
        // (BEP-47).
        for w in files.files.windows(2) {
            if w[0].attr.padding {
                assert_eq!(
                    w[1].v1_offset.unwrap_or(u64::MAX) % u64::from(files.piece_length),
                    0,
                    "files after a pad must be piece-aligned"
                );
            }
        }
        // a pad never ends the list (BEP-47: pads are placeholders).
        assert!(
            files.files.last().map(|f| !f.attr.padding).unwrap_or(true),
            "a pad must not end the list"
        );
    }
}

// ===== fixture byte-identity =====

#[tokio::test]
async fn hybrid_same_material_is_byte_identical_to_fixture() {
    let dir = temp_dir("fixture");
    let req = CreateRequest {
        name: "taiji-p01-hybrid".to_string(),
        files: vec![
            creator_file(&dir, "a.bin", &content_a(), FileAttr::default()),
            creator_file(&dir, "b.bin", &content_b(), FileAttr::default()),
        ],
        piece_length: 16384,
        form: TorrentForm::Hybrid,
        private: false,
        announce: Some("http://example.invalid/announce".to_string()),
        announce_list: None,
        comment: None,
        creation_date: None,
    };
    let created = ok(create(req).await, "create hybrid");

    // fixture: generated by the official creator algorithm, verified
    // against libtorrent 2.1.1.0.
    let fixture_path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/hybrid_16k.torrent");
    let fixture = ok(fs::read(&fixture_path), "read fixture");

    // byte identity implies matching infohash / piece layers / pad shape.
    assert_eq!(
        created.bytes, fixture,
        "a torrent generated from the same material must be byte-identical to the fixture"
    );

    // dual infohashes vs the fixture's expected constants (asserted
    // explicitly even though byte equality already implies it).
    assert_eq!(hex(&created.info_hash_v1), EXPECTED_V1, "v1 infohash");
    assert_eq!(hex(&created.info_hash_v2), EXPECTED_V2, "v2 infohash");

    // piece layers byte-identical (top-level dict value comparison).
    let (fixture_top, _) = ok(decode_with_info_span(&fixture), "decode fixture");
    let (created_top, _) = ok(decode_with_info_span(&created.bytes), "decode created");
    assert_eq!(
        created_top.get(b"piece layers"),
        fixture_top.get(b"piece layers"),
        "piece layers byte-identical to the fixture"
    );

    // self-validation loop.
    self_validate(&created, TorrentForm::Hybrid, &[70000, 30000]);
    fs::remove_dir_all(&dir).unwrap_or_else(|e| panic!("cleanup: {e}"));
}

// ===== form matrix: three forms x single/multi x tail/pad x attrs =====

/// Three forms x single/multi-file matrix: short tail (40000 = 2 pieces +
/// a 7232B tail), unaligned multi-file (pad alignment), attr h/x, private
/// passthrough, announce-list, and the optional top-level fields.
#[tokio::test]
async fn form_matrix_single_multi_short_tail_attrs() {
    let forms = [
        (TorrentForm::V1Only, "v1"),
        (TorrentForm::V2Only, "v2"),
        (TorrentForm::Hybrid, "hybrid"),
    ];
    for (form, tag) in forms {
        // ---- multi-file: unaligned boundary -> pad; attr hx / x; empty
        // file ----
        let dir = temp_dir(tag);
        let files = vec![
            creator_file(
                &dir,
                "d/a.bin",
                &content_a(),
                FileAttr {
                    hidden: true,
                    executable: true,
                    ..FileAttr::default()
                },
            ),
            creator_file(
                &dir,
                "b.bin",
                &content_b(),
                FileAttr {
                    executable: true,
                    ..FileAttr::default()
                },
            ),
            creator_file(&dir, "empty.bin", &[], FileAttr::default()),
            creator_file(&dir, "c.bin", &content_a()[..20000], FileAttr::default()),
        ];
        let mut req = base_request("matrix-multi", files, form);
        req.private = true;
        req.announce = Some("http://example.invalid/announce".to_string());
        req.announce_list = Some(vec![vec![
            "http://example.invalid/a".to_string(),
            "http://example.invalid/b".to_string(),
        ]]);
        req.comment = Some("matrix".to_string());
        req.creation_date = Some(1_700_000_000);
        let created = ok(create(req).await, "create multi");
        // length set in v1 layout order (d/a.bin, b.bin, empty.bin, c.bin).
        self_validate(&created, form, &[70000, 30000, 0, 20000]);

        let (top, _) = ok(decode_with_info_span(&created.bytes), "decode");
        // private passthrough (BEP-27).
        assert_eq!(get(get(&top, b"info"), b"private"), &Value::Int(1));
        // optional top-level fields + announce-list.
        assert!(top.get(b"announce").is_some());
        assert!(top.get(b"announce-list").is_some());
        assert!(top.get(b"comment").is_some());
        assert!(top.get(b"creation date").is_some());
        // form key faces: v2 forms must have meta version + piece layers;
        // v1 forms must have pieces; mutually exclusive (mirror of the
        // BEP-52 detect).
        let info = get(&top, b"info");
        assert_eq!(
            info.get(b"meta version").is_some(),
            matches!(form, SwarmKind::V2Only | SwarmKind::Hybrid)
        );
        assert_eq!(
            info.get(b"pieces").is_some(),
            matches!(form, SwarmKind::V1Only | SwarmKind::Hybrid)
        );
        assert_eq!(
            top.get(b"piece layers").is_some(),
            matches!(form, SwarmKind::V2Only | SwarmKind::Hybrid)
        );
        // attr passthrough: v1 files entries and v2 leaves both carry "hx"
        // (bencode value comparison).
        if matches!(form, SwarmKind::V1Only | SwarmKind::Hybrid) {
            let files_list = match get(info, b"files") {
                Value::List(l) => l,
                other => panic!("files not a list: {other:?}"),
            };
            assert_eq!(
                get(&files_list[0], b"attr"),
                &Value::Bytes(b"hx".to_vec()),
                "v1 files[0] attr"
            );
            // layout order: d/a.bin(70000) unaligned -> [.pad/11920] ->
            // b.bin -> empty.bin -> c.bin.
            assert_eq!(
                get(&files_list[1], b"attr"),
                &Value::Bytes(b"p".to_vec()),
                "pad entry attr = p (BEP47)"
            );
            assert_eq!(get(&files_list[2], b"attr"), &Value::Bytes(b"x".to_vec()));
        }
        if matches!(form, SwarmKind::V2Only | SwarmKind::Hybrid) {
            let tree = get(info, b"file tree");
            let leaf = get(get(tree, b"d"), b"a.bin");
            let props = get(leaf, b"");
            assert_eq!(
                get(props, b"attr"),
                &Value::Bytes(b"hx".to_vec()),
                "v2 leaf attr"
            );
            // empty file: no pieces root (BEP-52).
            let empty_props = get(get(get(tree, b"empty.bin"), b""), b"length");
            assert_eq!(empty_props, &Value::Int(0));
            assert!(
                get(get(tree, b"empty.bin"), b"")
                    .get(b"pieces root")
                    .is_none()
            );
        }
        fs::remove_dir_all(&dir).unwrap_or_else(|e| panic!("cleanup: {e}"));

        // ---- single-file: length/attr at info top level + tree wraps
        // under name ----
        let dir = temp_dir(tag);
        let mut req = base_request(
            "single.bin",
            vec![creator_file(
                &dir,
                "single.bin",
                &content_a(),
                FileAttr {
                    hidden: true,
                    ..FileAttr::default()
                },
            )],
            form,
        );
        req.private = true;
        let created = ok(create(req).await, "create single");
        self_validate(&created, form, &[70000]);
        let (top, _) = ok(decode_with_info_span(&created.bytes), "decode single");
        let info = get(&top, b"info");
        if matches!(form, SwarmKind::V1Only | SwarmKind::Hybrid) {
            assert_eq!(get(info, b"length"), &Value::Int(70000));
            assert_eq!(get(info, b"attr"), &Value::Bytes(b"h".to_vec()));
        }
        if matches!(form, SwarmKind::V2Only | SwarmKind::Hybrid) {
            let tree = get(info, b"file tree");
            assert!(
                tree.get(b"").is_none(),
                "a single-file tree root must not be a file (BEP52)"
            );
            let props = get(get(get(tree, b"single.bin"), b""), b"attr");
            assert_eq!(props, &Value::Bytes(b"h".to_vec()));
        }
        fs::remove_dir_all(&dir).unwrap_or_else(|e| panic!("cleanup: {e}"));
    }
}

/// Short-tail + pad alignment numeric assertions (hybrid multi-file, 64KiB
/// pieces: a piece boundary falls inside a file; pads only align following
/// files; the v1 short tail is not zero-padded).
#[tokio::test]
async fn short_tail_and_pad_alignment_numeric() {
    let dir = temp_dir("pad-align");
    // layout: a.bin[0, 65537) + .pad[65537, 131072) (65535) +
    // b.bin[131072, 163840).
    let a_content = &content_a()[..65537];
    let files = vec![
        creator_file(&dir, "a.bin", a_content, FileAttr::default()),
        creator_file(&dir, "b.bin", &[0x5a; 32768], FileAttr::default()),
    ];
    let mut req = base_request("pad-align", files, TorrentForm::Hybrid);
    req.piece_length = 64 * 1024;
    let created = ok(create(req).await, "create");
    let (top, _) = ok(decode_with_info_span(&created.bytes), "decode");

    let files_view = ok(filetree::parse_v1_files(&top), "parse_v1_files");
    assert_eq!(files_view.piece_length, 64 * 1024);
    let (a, pad, b) = (
        &files_view.files[0],
        &files_view.files[1],
        &files_view.files[2],
    );
    assert_eq!(
        (a.path.display().to_string(), a.length),
        ("a.bin".to_string(), 65537)
    );
    assert_eq!(
        (pad.attr.padding, pad.length, pad.v1_offset),
        (true, 65535, Some(65537)),
        "pad length = the slack up to the next piece boundary (BEP47 L85)"
    );
    assert_eq!(
        b.v1_offset,
        Some(131072),
        "the file after a pad starts at a piece boundary"
    );
    // v1 piece count = ceil(163840 / 65536) = 3.
    let info = get(&top, b"info");
    let pieces = match get(info, b"pieces") {
        Value::Bytes(b) => b.clone(),
        other => panic!("pieces not bytes: {other:?}"),
    };
    assert_eq!(pieces.len() / 20, 3);
    // piece 1 = a.bin's byte 65537 onward + the pad's 65535B zero span —
    // zero spans are hashed.
    let mut piece1 = Sha1::new();
    piece1.update(&a_content[65536..]);
    piece1.update([0u8; 65535]);
    assert_eq!(
        &pieces[20..40],
        &piece1.finalize()[..],
        "the pad zero span counts into the v1 hash"
    );
    // piece 2 = b.bin's real 32768B; a short tail is not padded.
    let mut piece2 = Sha1::new();
    piece2.update([0x5a; 32768]);
    assert_eq!(
        &pieces[40..60],
        &piece2.finalize()[..],
        "the short tail piece = real bytes"
    );
    // v2 layer: a.bin 65537B = 2 pieces (layer has 2 entries, re-validated
    // inside parse); b.bin 32768B = 1 piece (no entry, BEP-52 piece layers
    // section).
    let tree_files = ok(filetree::parse(&top), "parse");
    assert_eq!(tree_files.files[0].path.display().to_string(), "a.bin");
    assert_eq!(tree_files.files[0].length, 65537);
    assert_eq!(
        tree_files.files[0]
            .piece_layer
            .as_ref()
            .map(|layer| layer.len()),
        Some(64),
        "a.bin = 2 pieces -> a 64B piece layers entry"
    );
    assert_eq!(tree_files.files[1].path.display().to_string(), "b.bin");
    assert!(
        tree_files.files[1].piece_layer.is_none(),
        "b.bin <= 1 piece -> no layer entry"
    );
    fs::remove_dir_all(&dir).unwrap_or_else(|e| panic!("cleanup: {e}"));
}

