// ===== roundtrip property: create -> parse invariants =====

/// Non-conflicting path pool (no prefix relations; covers two nesting
/// levels).
const PATH_POOL: [&str; 6] = ["a.bin", "b.bin", "d/a.bin", "d/b.bin", "e/f/c.bin", "zz"];

proptest! {
    #![proptest_config(proptest::test_runner::Config::with_cases(48))]

    #[test]
    fn create_parse_roundtrip_invariants(
        picks in prop::collection::btree_set(0usize..PATH_POOL.len(), 2..=4),
        mut lengths in prop::collection::vec(0u64..50_000, 4),
        piece_exp in 0u8..3,
        seed in any::<u64>(),
    ) {
        // 16384 / 32768 / 65536 (BEP-52: power of two >= 16KiB).
        let piece_length = (16 * 1024u32) << piece_exp;
        // the first file is never empty (picks always take lengths[0]
        // first; an all-empty set is explicitly rejected).
        lengths[0] = lengths[0].max(1);
        let dir = temp_dir("prop");
        let mut files = Vec::new();
        let mut want_lengths = Vec::new();
        for (i, idx) in picks.iter().enumerate() {
            let length = lengths[i % lengths.len()];
            let content: Vec<u8> = (0..length)
                .map(|j| ((j ^ seed).wrapping_mul(2654435761) >> 24) as u8)
                .collect();
            files.push(creator_file(&dir, PATH_POOL[*idx], &content, FileAttr::default()));
            want_lengths.push(length);
        }
        let req = CreateRequest {
            name: "prop".to_string(),
            files,
            piece_length,
            form: TorrentForm::Hybrid,
            private: false,
            announce: None,
            announce_list: None,
            comment: None,
            creation_date: None,
        };
        let created = match create_blocking(req) {
            Ok(c) => c,
            Err(e) => panic!("create failed: {e}"),
        };
        // create -> parse roundtrip: all parse faces pass + file set/
        // lengths match + pad alignment + dual infohashes recompute over
        // the raw slice.
        self_validate(&created, TorrentForm::Hybrid, &want_lengths);
        fs::remove_dir_all(&dir).unwrap_or_else(|e| panic!("cleanup: {e}"));
    }
}

/// Identical-content regression (a pinned property-shrink sample, not the
/// random strategy): a.bin(1) / b.bin(44003) / d/a.bin(0) / d/b.bin(44003)
/// @16KiB hybrid and v2-only — b.bin and d/b.bin share content => same
/// merkle root => `piece layers` keys by root and duplicate keys cannot be
/// canonically encoded (bencode dict keys are unique). create used to fail
/// with internal inconsistency; same roots now collapse to one entry
/// (BEP-52 pieces root section "identical files always result in the same
/// root hash"; libtorrent create_torrent.cpp writes by key and
/// overwrites, the same collapse).
#[test]
fn identical_content_files_share_piece_layers_entry() {
    for form in [TorrentForm::Hybrid, TorrentForm::V2Only] {
        let dir = temp_dir("dup-root");
        // the same deterministic content generator as the property
        // (seed = 0).
        let make_content = |len: u64| -> Vec<u8> {
            (0..len)
                .map(|j| (j.wrapping_mul(2654435761) >> 24) as u8)
                .collect()
        };
        let req = CreateRequest {
            name: "prop".to_string(),
            files: vec![
                creator_file(&dir, "a.bin", &make_content(1), FileAttr::default()),
                creator_file(&dir, "b.bin", &make_content(44003), FileAttr::default()),
                creator_file(&dir, "d/a.bin", &[], FileAttr::default()),
                creator_file(&dir, "d/b.bin", &make_content(44003), FileAttr::default()),
            ],
            piece_length: 16384,
            form,
            private: false,
            announce: None,
            announce_list: None,
            comment: None,
            creation_date: None,
        };
        let created = ok(create_blocking(req), "same-content files must create");
        self_validate(&created, form, &[1, 44003, 0, 44003]);

        let (top, _) = ok(decode_with_info_span(&created.bytes), "decode");
        // v2 face: both identical-content leaves have equal roots + piece
        // layers collapses to one 96B entry (44003B @16KiB = 3 pieces x
        // 32B).
        let tree = get(get(&top, b"info"), b"file tree");
        let root_of = |path: &[&str]| -> Vec<u8> {
            let mut node = tree.clone();
            for k in path {
                node = get(&node, k.as_bytes()).clone();
            }
            match get(get(&node, b""), b"pieces root") {
                Value::Bytes(b) => b.clone(),
                other => panic!("pieces root not bytes: {other:?}"),
            }
        };
        assert_eq!(
            root_of(&["b.bin"]),
            root_of(&["d", "b.bin"]),
            "identical content files share the same root (BEP52)"
        );
        let Value::Dict(pairs) = get(&top, b"piece layers") else {
            panic!("piece layers must be a dict");
        };
        assert_eq!(
            pairs.len(),
            1,
            "the same root must collapse to one entry (unique dict key)"
        );
        assert_eq!(
            pairs[0].0,
            root_of(&["b.bin"]),
            "the key = the shared merkle root"
        );
        match &pairs[0].1 {
            Value::Bytes(b) => assert_eq!(b.len(), 96, "3 piece layers concatenated"),
            other => panic!("layer not bytes: {other:?}"),
        }
        // v1 layout corner (hybrid only): a zero-length file triggers no
        // pad, and alignment is inserted before the next non-empty file
        // (BEP-47) — pad planning is not disturbed by the
        // identical-content /empty-file combination.
        if matches!(form, SwarmKind::Hybrid) {
            let files_view = ok(filetree::parse_v1_files(&top), "parse_v1_files");
            let shape: Vec<(String, u64, bool)> = files_view
                .files
                .iter()
                .map(|f| (f.path.display().to_string(), f.length, f.attr.padding))
                .collect();
            assert_eq!(
                shape,
                vec![
                    ("a.bin".to_string(), 1, false),
                    (".pad/16383".to_string(), 16383, true),
                    ("b.bin".to_string(), 44003, false),
                    ("d/a.bin".to_string(), 0, false),
                    (".pad/5149".to_string(), 5149, true),
                    ("d/b.bin".to_string(), 44003, false),
                ],
                "a 0-length file triggers no pad; an alignment pad is inserted before the next non-empty file"
            );
        }
        fs::remove_dir_all(&dir).unwrap_or_else(|e| panic!("cleanup: {e}"));
    }
}
